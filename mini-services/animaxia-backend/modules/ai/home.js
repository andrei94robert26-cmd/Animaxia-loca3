async function metadataData() {
  const key = 'aihome:metadata';
  const hit = cache.get(key);
  if (hit) return hit;

  const [lib, franchiseHub, trilogyHub] = await Promise.all([
    listContent({ page: 1, limit: 100, sort: 'createdat' }),
    getFranchiseHub().catch(() => ({ data: [] })),
    getTrilogyHub().catch(() => ({ data: [] })),
  ]);
  const enrichment = (await readEnrichment()).entries || {};
  const libRows = lib.data || []; // (renamed: `rows` is the SQL helper import)

  const dims = {
    year: new Map(),
    genre: new Map(),
    category: new Map(),
    studio: new Map(),
    actor: new Map(),
    collection: new Map(),
  };

  const bump = (map, value, inc = 1) => {
    const name = String(value || '').trim();
    if (!name) return;
    map.set(name, (map.get(name) || 0) + inc);
  };

  let withYear = 0;
  let withGenres = 0;
  let withDescription = 0;
  let withStudio = 0;
  let withCast = 0;
  let withCollection = 0;

  for (const row of libRows) {
    const md = row.metadata || {};
    const ext = String(row.externalid || '');
    const entry = enrichment[ext]; // enrichment by exact externalid key
    bump(dims.category, categoryLabel(row.type));
    const year = md.year || entry?.year;
    if (year) {
      bump(dims.year, String(year));
      withYear += 1;
    }
    const genres = Array.isArray(md.genres) && md.genres.length ? md.genres : entry?.genres || [];
    if (genres.length) withGenres += 1;
    for (const g of genres) bump(dims.genre, g);
    if (md.overview || md.synopsis || md.description || entry?.overview) withDescription += 1;
    const studios = entry?.studios || [];
    if (studios.length) withStudio += 1;
    for (const s of studios) bump(dims.studio, s);
    const cast = entry?.cast || [];
    if (cast.length) withCast += 1;
    for (const a of cast) bump(dims.actor, a);
    if (entry?.collection) {
      bump(dims.collection, entry.collection);
      withCollection += 1;
    }
  }

  // Enrichment-only entries (trending pool) contribute studio/actor metadata.
  for (const entry of Object.values(enrichment)) {
    for (const s of entry.studios || []) bump(dims.studio, s, 0); // no count inflation
    for (const a of entry.cast || []) bump(dims.actor, a, 0);
    if (entry.collection) bump(dims.collection, entry.collection, 0);
  }

  const trailers = await readTrailers();

  const payload = {
    ai: true,
    generatedAt: new Date().toISOString(),
    enriching: {
      pool: Object.keys(enrichment).length,
      enriched: Object.values(enrichment).filter((e) => e && e.fetchedAt).length,
      ttlHours: ENRICH_TTL_MS / 3600000,
    },
    coverage: {
      titles: lib.total,
      withYear,
      withGenres,
      withDescription,
      withStudio,
      withCast,
      withCollection,
      withTrailer: Object.keys(trailers.entries).length,
    },
    dimensions: {
      year: [...dims.year.entries()].map(([value, count]) => ({ value, count })).sort((a, b) => b.value.localeCompare(a.value)),
      genre: [...dims.genre.entries()].map(([value, count]) => ({ value, count })).sort((a, b) => b.count - a.count || a.value.localeCompare(b.value)),
      category: [...dims.category.entries()].map(([value, count]) => ({ value, count })).sort((a, b) => b.count - a.count || a.value.localeCompare(b.value)),
      studio: [...dims.studio.entries()].map(([value, count]) => ({ value, count })).sort((a, b) => b.count - a.count || a.value.localeCompare(b.value)),
      actor: [...dims.actor.entries()].map(([value, count]) => ({ value, count })).sort((a, b) => b.count - a.count || a.value.localeCompare(b.value)).slice(0, 60),
      collection: [...dims.collection.entries()].map(([value, count]) => ({ value, count })).sort((a, b) => b.count - a.count || a.value.localeCompare(b.value)),
      franchise: (franchiseHub.data || []).map((c) => ({ value: c.name, count: c.partCount })),
      trilogy: (trilogyHub.data || [])
        .filter((c) => c.partCount === 3)
        .map((c) => ({ value: c.name, count: c.partCount })),
    },
  };
  cache.set(key, payload, METADATA_TTL_MS);
  return payload;
}

