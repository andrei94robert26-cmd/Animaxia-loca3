const CATEGORY_LABELS = {
  movie: 'Film',
  tv: 'Serial TV',
  anime: 'Anime',
  db: 'Bibliotecă',
  news: 'Știri',
  mined: 'Conținut minat',
  featured: 'Recomandat',
};

function categoryLabel(type) {
  return CATEGORY_LABELS[type] || String(type || '').replace(/^\w/, (c) => c.toUpperCase());
}

async function taxonomyData() {
  const key = 'aihome:taxonomy';
  const hit = cache.get(key);
  if (hit) return hit;

  const [lib, extChunk1] = await Promise.all([
    listContent({ page: 1, limit: 100, sort: 'createdat' }),
    externalChunk(1).catch(() => []),
  ]);

  const genreCounts = new Map();
  const categoryCounts = new Map();
  const decadeCounts = new Map();
  let analyzed = 0;

  const account = (item, typeOverride) => {
    analyzed += 1;
    const type = typeOverride || item.mediaType || item.type;
    const cat = categoryLabel(type);
    categoryCounts.set(cat, (categoryCounts.get(cat) || 0) + 1);
    for (const g of item.genres || []) {
      const name = String(g).trim();
      if (!name) continue;
      genreCounts.set(name, (genreCounts.get(name) || 0) + 1);
    }
    const year = parseInt(item.year, 10);
    if (Number.isInteger(year) && year > 1900) {
      const decade = `${Math.floor(year / 10) * 10}s`;
      decadeCounts.set(decade, (decadeCounts.get(decade) || 0) + 1);
    }
  };

  for (const row of lib.data || []) {
    account(libraryItem(row), row.type);
  }
  for (const item of extChunk1) account(item);

  const payload = {
    ai: true,
    generatedAt: new Date().toISOString(),
    analyzedItems: analyzed,
    sourcesChecked: ['neon-library', 'tmdb-trending', 'jikan-top'],
    genres: [...genreCounts.entries()]
      .map(([name, count]) => ({ name, count }))
      .sort((a, b) => b.count - a.count || a.name.localeCompare(b.name))
      .slice(0, 48),
    categories: [...categoryCounts.entries()]
      .map(([name, count]) => ({ name, count }))
      .sort((a, b) => b.count - a.count || a.name.localeCompare(b.name)),
    decades: [...decadeCounts.entries()]
      .map(([name, count]) => ({ name, count }))
      .sort((a, b) => b.name.localeCompare(a.name)),
  };
  cache.set(key, payload, TAXONOMY_TTL_MS);
  return payload;
}

