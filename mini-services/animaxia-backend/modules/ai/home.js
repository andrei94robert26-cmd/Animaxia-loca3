const EXTERNAL_SOURCE_RE = /^(tmdb|jikan|miner|https?)/i;

async function externalStats(since) {
  const key = `aihome:stats:${since || ''}`;
  const hit = cache.get(key);
  if (hit) return hit;

  const lib = await listContent({ page: 1, limit: 100, sort: 'createdat' });
  const rows = lib.data || [];

  const bySource = {};
  let postersFromExternal = 0;
  let contentsFromExternal = 0;
  let withGenres = 0;
  let withYear = 0;
  let withDescription = 0;
  const recent = [];
  let newSince = 0;

  for (const row of rows) {
    const md = row.metadata || {};
    const source = String(md.source || (row.externalid || '').split(':')[0] || 'seed').toLowerCase();
    const isExternal = EXTERNAL_SOURCE_RE.test(source);
    bySource[source] = (bySource[source] || 0) + 1;
    if (isExternal) contentsFromExternal += 1;
    if (isExternal && (row.thumbnail || md.backdrop)) postersFromExternal += 1;
    if (Array.isArray(md.genres) && md.genres.length) withGenres += 1;
    if (md.year) withYear += 1;
    if (md.overview || md.synopsis || md.description) withDescription += 1;
    const created = row.createdat ? new Date(row.createdat) : null;
    if (created && since && created.getTime() > new Date(since).getTime()) newSince += 1;
  }

  const recentRows = rows.slice(0, 12).map((row) => {
    const md = row.metadata || {};
    return {
      id: row.id,
      title: row.title,
      type: row.type,
      source: String(md.source || (row.externalid || '').split(':')[0] || 'seed'),
      externalid: row.externalid || null,
      hasPoster: Boolean(row.thumbnail || md.backdrop),
      createdat: row.createdat || null,
    };
  });
  recent.push(...recentRows);

  // Live external catalog sizes (short-cached upstream calls, degrade to null).
  const [trendingSize, tvSize, jikanSize] = await Promise.all([
    tmdbFetch('/trending/movie/week', { page: 1 })
      .then((p) => (typeof p?.total_results === 'number' ? p.total_results : null))
      .catch(() => null),
    tmdbFetch('/trending/tv/week', { page: 1 })
      .then((p) => (typeof p?.total_results === 'number' ? p.total_results : null))
      .catch(() => null),
    jikanFetch('/top/anime', { page: 1, limit: 20 }, 1)
      .then((p) => {
        const items = Array.isArray(p?.data) ? p.data.length : 0;
        return items > 0 ? items * 500 : null; // Jikan exposes ~500 pages
      })
      .catch(() => null),
  ]);

  const payload = {
    ai: true,
    live: true,
    updatedAt: new Date().toISOString(),
    library: {
      total: lib.total,
      withGenres,
      withYear,
      withDescription,
      bySource,
    },
    posters: { totalInLibrary: postersFromExternal, fromExternal: postersFromExternal },
    contents: { totalInLibrary: lib.total, fromExternal: contentsFromExternal },
    externalCatalog: {
      tmdbTrendingMovies: trendingSize,
      tmdbTrendingTv: tvSize,
      jikanTop: jikanSize,
      checkedAt: new Date().toISOString(),
    },
    recent,
    delta: since ? { since, newItems: newSince } : null,
  };
  cache.set(key, payload, STATS_TTL_MS);
  return payload;
}

/* ------------------------- metadata enrichment pool ------------------------- */
/*
 * The AI extractor pulls the full metadata surface (year, genres, studio,
 * actors, collection, franchise hints, description, trailer) for existing
 * content. Library rows only carry partial metadata, so we enrich:
 *   - tmdb:movie:X / tmdb:tv:X  → TMDB detail with credits + videos
 *   - jikan:anime:X             → Jikan detail (studios, trailer)
 *   - trending head             → a small rotating pool of live items
 * FAZA 16-a: entries persist for 24h (TTL by updatedat) in the Neon
 * `aienrichment` table when postgres is active; data/ai-home-enrichment.json
 * remains only as the local-fallback driver store. Every /metadata call
 * grows the pool in the background (a few items at a time).
 */

async function readEnrichment() {
  if (pgActive()) {
    try {
      const r = await rows('SELECT externalid, payload FROM aienrichment');
      const entries = {};
      for (const row of r) entries[row.externalid] = parseJsonb(row.payload, {});
      return { entries };
    } catch (err) {
      logger.warn(`[ai-home] aienrichment read failed (${err.message}) — empty pool`);
      return { entries: {} };
    }
  }
  return loadJson(ENRICH_FILE, { entries: {} });
}

/** Persist one enrichment entry (Neon upsert, or file store in fallback mode). */
async function putEnrichmentEntry(entry) {
  if (!entry?.key) return;
  if (pgActive()) {
    try {
      await rows(
        `INSERT INTO aienrichment (externalid, payload) VALUES ($1, $2)
         ON CONFLICT (externalid) DO UPDATE SET payload = EXCLUDED.payload, updatedat = CURRENT_TIMESTAMP`,
        [entry.key, jsonb(entry)],
      );
    } catch (err) {
      logger.warn(`[ai-home] aienrichment write failed for ${entry.key}: ${err.message}`);
    }
    return;
  }
  const store = loadJson(ENRICH_FILE, { entries: {} });
  store.entries[entry.key] = entry;
  saveJson(ENRICH_FILE, store);
}

function firstTrailerKeyOf(videos) {
  const results = Array.isArray(videos?.results) ? videos.results : [];
  const trailer =
    results.find((v) => v.type === 'Trailer' && v.site === 'YouTube') ||
    results.find((v) => v.site === 'YouTube');
  return trailer ? trailer.key : null;
}

