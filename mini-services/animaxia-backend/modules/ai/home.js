function normalizeTmdbListItem(item, mediaType, genreMap) {
  if (!item || !item.id) return null;
  const genres = Array.isArray(item.genre_ids)
    ? item.genre_ids.map((id) => genreMap[id]).filter(Boolean)
    : Array.isArray(item.genres)
      ? item.genres.map((g) => g.name).filter(Boolean)
      : [];
  return {
    id: item.id,
    title: item.title || item.name || 'Untitled',
    image: item.poster_path ? `${TMDB_IMAGE_BASE}/w500${item.poster_path}` : null,
    backdrop: item.backdrop_path ? `${TMDB_IMAGE_BASE}/w780${item.backdrop_path}` : null,
    overview: item.overview || '',
    rating: item.vote_average ?? null,
    year: (item.release_date || item.first_air_date || '').slice(0, 4) || null,
    mediaType,
    genres,
    source: 'tmdb',
  };
}

function normalizeJikanListItem(item) {
  if (!item || !item.mal_id) return null;
  return {
    id: item.mal_id,
    title: item.title || item.title_english || 'Untitled',
    image:
      item.images?.jpg?.large_image_url ||
      item.images?.webp?.large_image_url ||
      item.images?.jpg?.image_url ||
      null,
    backdrop: item.trailer?.images?.maximum_image_url || null,
    overview: item.synopsis || '',
    rating: item.score ?? item.scored ?? null,
    year: item.year || (item.aired?.from ? String(item.aired.from).slice(0, 4) : null),
    mediaType: 'anime',
    genres: (item.genres || []).map((g) => g.name),
    source: 'jikan',
  };
}

/**
 * External source-page k: interleave TMDB trending movies + trending TV +
 * Jikan top anime into one deterministic stream. Cached for CHUNK_TTL_MS so
 * walking pages stays stable. Failures degrade to partial chunks.
 */
async function externalChunk(k) {
  const key = `aihome:extchunk:${k}`;
  const hit = cache.get(key);
  if (hit) return hit;

  const [mv, tv, an] = await Promise.allSettled([
    (async () => {
      const payload = await tmdbFetch('/trending/movie/week', { page: k });
      const map = await getGenreMap('movie');
      return (payload?.results || []).map((i) => normalizeTmdbListItem(i, 'movie', map)).filter(Boolean);
    })(),
    (async () => {
      const payload = await tmdbFetch('/trending/tv/week', { page: k });
      const map = await getGenreMap('tv');
      return (payload?.results || []).map((i) => normalizeTmdbListItem(i, 'tv', map)).filter(Boolean);
    })(),
    (async () => {
      const payload = await jikanFetch('/top/anime', { page: k, limit: 20 }, 3);
      return (payload?.data || []).map(normalizeJikanListItem).filter(Boolean);
    })(),
  ]);

  const movies = mv.status === 'fulfilled' ? mv.value : [];
  const tvs = tv.status === 'fulfilled' ? tv.value : [];
  const animes = an.status === 'fulfilled' ? an.value : [];
  const maxLen = Math.max(movies.length, tvs.length, animes.length);
  const interleaved = [];
  for (let i = 0; i < maxLen; i += 1) {
    if (movies[i]) interleaved.push(movies[i]);
    if (tvs[i]) interleaved.push(tvs[i]);
    if (animes[i]) interleaved.push(animes[i]);
  }
  cache.set(key, interleaved, CHUNK_TTL_MS);
  return interleaved;
}

/**
 * Walk the interleaved external stream starting at `offset`, collecting up to
 * `count` items. Chunks are disjoint (each is a different TMDB/Jikan page),
 * so pages stay deterministic within the chunk cache TTL.
 */
async function externalSlice(offset, count) {
  const items = [];
  let k = 1;
  let pos = Math.max(0, offset);
  while (items.length < count && k <= MAX_K) {
    let chunk = [];
    try {
      chunk = await externalChunk(k);
    } catch {
      break;
    }
    if (pos >= chunk.length) {
      pos -= chunk.length;
      k += 1;
      continue;
    }
    while (pos < chunk.length && items.length < count) {
      items.push(chunk[pos]);
      pos += 1;
    }
    if (pos >= chunk.length) {
      pos = 0;
      k += 1;
    }
  }
  return items;
}

/** Library rows normalized to the same feed item shape (mediaType 'db'). */
function libraryItem(row) {
  const md = row.metadata || {};
  return {
    id: row.id,
    title: row.title || 'Untitled',
    image: row.thumbnail || md.backdrop || null,
    backdrop: md.backdrop || null,
    overview: md.overview || md.synopsis || md.description || '',
    rating: typeof md.rating === 'number' ? md.rating : typeof md.score === 'number' ? md.score : null,
    year: md.year != null ? String(md.year) : null,
    mediaType: 'db',
    genres: Array.isArray(md.genres) ? md.genres.map(String) : [],
    source: 'neon',
  };
}

async function buildFeedPage(page, limit) {
  const lib = await listContent({ page, limit, sort: 'createdat' });
  const libTotal = lib.total || 0;
  const libTotalPages = Math.max(1, Math.ceil(libTotal / limit));

  let items = [];
  let sourceMode = 'library';

  if (page <= libTotalPages) {
    items = (lib.data || []).map(libraryItem);
    if (page === libTotalPages && items.length < limit) {
      // Partial last library page — the head of the external stream fills it,
      // so the external stream is pre-consumed by `limit - items.length`.
      const fill = await externalSlice(0, limit - items.length);
      items = items.concat(fill);
      if (fill.length > 0) sourceMode = 'library+external';
    }
  } else {
    // Purely external page. How much of the external stream was already
    // consumed while filling the (possibly partial) last library page:
    const onLastLibPage = libTotal === 0 ? 0 : libTotal % limit || limit;
    const consumed = libTotal === 0 ? limit : limit - onLastLibPage === limit ? 0 : limit - onLastLibPage;
    const offset = consumed + (page - libTotalPages - 1) * limit;
    items = await externalSlice(offset, limit);
    sourceMode = 'external';
  }

  const totalPages = Math.min(MAX_PAGES, libTotalPages + 60);
  return {
    ai: true,
    engine: 'ai-infinite-feed',
    page,
    limit,
    totalPages,
    totalItems: totalPages * limit,
    hasNextPage: page < totalPages && items.length > 0,
    hasPrevPage: page > 1,
    sourceMode,
    items,
    generatedAt: new Date().toISOString(),
  };
}

