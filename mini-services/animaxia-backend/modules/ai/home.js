const BROWSE_DIMS = new Set(['year', 'genre', 'category', 'studio', 'actor', 'collection', 'franchise', 'trilogy']);

function enrichmentToItem(entry) {
  return {
    id: entry.id,
    title: entry.title,
    image: entry.image,
    backdrop: null,
    overview: entry.overview,
    rating: entry.rating,
    year: entry.year ? String(entry.year) : null,
    mediaType: entry.mediaType,
    genres: entry.genres || [],
    source: entry.kind === 'jikan' ? 'jikan' : 'tmdb',
  };
}

async function browse(dim, value, page, limit) {
  if (!BROWSE_DIMS.has(dim)) return { error: `Unknown dimension '${dim}'` };
  const needle = String(value || '').trim().toLowerCase();
  if (!needle) return { error: 'Missing value parameter' };

  const items = [];
  const seen = new Set();
  const push = (item) => {
    if (!item) return;
    const key = `${item.mediaType}:${item.id}`;
    if (seen.has(key)) return;
    seen.add(key);
    items.push(item);
  };

  const [lib, franchiseHub, trilogyHub] = await Promise.all([
    listContent({ page: 1, limit: 100, sort: 'createdat' }),
    dim === 'franchise' ? getFranchiseHub().catch(() => ({ data: [] })) : Promise.resolve({ data: [] }),
    dim === 'trilogy' ? getTrilogyHub().catch(() => ({ data: [] })) : Promise.resolve({ data: [] }),
  ]);
  const enrichment = (await readEnrichment()).entries || {};

  // Franchise / trilogy browse: the real TMDB collection parts, in order.
  if (dim === 'franchise' || dim === 'trilogy') {
    const hub = dim === 'franchise' ? franchiseHub : trilogyHub;
    const match = (hub.data || []).find(
      (c) => c.name.toLowerCase() === needle || c.name.toLowerCase().startsWith(needle),
    );
    if (match) {
      for (const part of match.parts || []) push(part);
    }
  }

  for (const row of lib.data || []) {
    const md = row.metadata || {};
    const entry = enrichment[String(row.externalid || '')];
    let hit = false;
    switch (dim) {
      case 'year':
        hit = String(md.year ?? entry?.year ?? '') === needle;
        break;
      case 'genre':
        hit = [...(md.genres || []), ...(entry?.genres || [])].some((g) => String(g).toLowerCase() === needle);
        break;
      case 'category':
        hit = categoryLabel(row.type).toLowerCase() === needle || String(row.type).toLowerCase() === needle;
        break;
      case 'studio':
        hit = (entry?.studios || []).some((s) => s.toLowerCase() === needle);
        break;
      case 'actor':
        hit = (entry?.cast || []).some((a) => a.toLowerCase() === needle);
        break;
      case 'collection':
        hit = String(entry?.collection || '').toLowerCase() === needle;
        break;
      default:
        hit = false;
    }
    if (hit) push(libraryItem(row));
  }

  // Enrichment pool (library-linked + trending) — richer than row metadata.
  if (dim !== 'franchise' && dim !== 'trilogy') {
    for (const entry of Object.values(enrichment)) {
      let hit = false;
      switch (dim) {
        case 'year':
          hit = String(entry.year ?? '') === needle;
          break;
        case 'genre':
          hit = (entry.genres || []).some((g) => g.toLowerCase() === needle);
          break;
        case 'category':
          hit = categoryLabel(entry.mediaType).toLowerCase() === needle;
          break;
        case 'studio':
          hit = (entry.studios || []).some((s) => s.toLowerCase() === needle);
          break;
        case 'actor':
          hit = (entry.cast || []).some((a) => a.toLowerCase() === needle);
          break;
        case 'collection':
          hit = String(entry.collection || '').toLowerCase() === needle;
          break;
        default:
          hit = false;
      }
      if (hit) push(enrichmentToItem(entry));
    }
  }

  // Live external feeds for the crowd dimensions (year / genre / category).
  if (items.length < limit * 3 && (dim === 'year' || dim === 'genre' || dim === 'category')) {
    for (let k = 1; k <= 2; k += 1) {
      let chunk = [];
      try {
        chunk = await externalChunk(k);
      } catch {
        break;
      }
      for (const item of chunk) {
        let hit = false;
        if (dim === 'year') hit = String(item.year ?? '') === needle;
        else if (dim === 'genre') hit = (item.genres || []).some((g) => g.toLowerCase() === needle);
        else hit = categoryLabel(item.mediaType).toLowerCase() === needle;
        if (hit) push(item);
      }
    }
  }

  const total = items.length;
  const totalPages = Math.max(1, Math.ceil(total / limit));
  const start = (page - 1) * limit;
  const sorted =
    dim === 'year'
      ? items.sort((a, b) => Number(b.rating || 0) - Number(a.rating || 0))
      : items;

  return {
    ai: true,
    dim,
    value,
    page,
    limit,
    total,
    totalPages,
    hasNextPage: page < totalPages,
    hasPrevPage: page > 1,
    items: sorted.slice(start, start + limit),
    generatedAt: new Date().toISOString(),
  };
}

