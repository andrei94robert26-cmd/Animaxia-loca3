/*
 * FAZA 16-a: resolved trailers persist for 7 days (TTL by updatedat) in the
 * Neon `aitrailercache` table when postgres is active; the data/*.json file
 * remains only as the local-fallback driver store.
 */

async function readTrailers() {
  if (pgActive()) {
    try {
      const r = await rows('SELECT cachekey, payload FROM aitrailercache');
      const entries = {};
      for (const row of r) entries[row.cachekey] = parseJsonb(row.payload, {});
      return { entries };
    } catch (err) {
      logger.warn(`[ai-home] aitrailercache read failed (${err.message}) — empty cache`);
      return { entries: {} };
    }
  }
  return loadJson(TRAILER_FILE, { entries: {} });
}

/** Fetch one cached trailer entry (Neon point-read, or file store). */
async function getTrailerEntry(key) {
  if (pgActive()) {
    try {
      const row = await one('SELECT payload FROM aitrailercache WHERE cachekey = $1', [key]);
      return row ? parseJsonb(row.payload, null) : null;
    } catch (err) {
      logger.warn(`[ai-home] aitrailercache point-read failed for ${key}: ${err.message}`);
      return null;
    }
  }
  const store = loadJson(TRAILER_FILE, { entries: {} });
  return store.entries[key] ?? null;
}

async function rememberTrailer(key, record) {
  const payload = {
    trailerKey: record.trailerKey,
    provider: record.provider,
    title: record.title || null,
    fetchedAt: new Date().toISOString(),
  };
  if (pgActive()) {
    try {
      await rows(
        `INSERT INTO aitrailercache (cachekey, payload) VALUES ($1, $2)
         ON CONFLICT (cachekey) DO UPDATE SET payload = EXCLUDED.payload, updatedat = CURRENT_TIMESTAMP`,
        [key, jsonb(payload)],
      );
    } catch (err) {
      logger.warn(`[ai-home] aitrailercache write failed for ${key}: ${err.message}`);
    }
    return;
  }
  const store = loadJson(TRAILER_FILE, { entries: {} });
  store.entries[key] = payload;
  saveJson(TRAILER_FILE, store);
}

async function searchYouTubeId(title) {
  const key = process.env.YOUTUBEAPIKEY;
  if (!key || !title) return null;
  const data = await fetchProviderJson('youtube', `${YOUTUBE_BASE}/search`, {
    params: {
      part: 'snippet',
      q: `${title} official trailer`,
      type: 'video',
      maxResults: 1,
      videoEmbeddable: 'true',
      key,
    },
    timeoutMs: 10000,
    retries: 1,
  });
  return data?.items?.[0]?.id?.videoId || null;
}

async function resolveTrailer(rawKey, title) {
  const key = String(rawKey || '').trim();
  if (!key) return { error: 'Missing key parameter' };

  const cached = await getTrailerEntry(key);
  const fresh =
    cached && Date.now() - new Date(cached.fetchedAt).getTime() < TRAILER_TTL_MS;
  if (fresh) {
    return {
      key,
      trailerKey: cached.trailerKey,
      provider: cached.provider,
      title: cached.title || title || null,
      embedUrl: cached.trailerKey ? `https://www.youtube.com/embed/${cached.trailerKey}?autoplay=1&mute=1&controls=0&rel=0` : null,
      cached: true,
      fetchedAt: cached.fetchedAt,
    };
  }

  let trailerKey = null;
  let provider = null;
  let resolvedTitle = title || null;

  // 1. Enrichment store (enrichment runs ahead of the cursor).
  const enrichment = (await readEnrichment()).entries || {};
  if (enrichment[key]?.trailerKey) {
    trailerKey = enrichment[key].trailerKey;
    provider = enrichment[key].kind === 'tmdb' ? 'tmdb-videos' : 'jikan';
    resolvedTitle = resolvedTitle || enrichment[key].title;
  }

  // 2. Direct hub resolution.
  if (!trailerKey) {
    let m;
    if ((m = /^tmdb:(movie|tv):(\d+)$/.exec(key))) {
      try {
        const videos = await tmdbFetch(`/${m[1]}/${m[2]}/videos`, {});
        trailerKey = firstTrailerKeyOf(videos);
        if (trailerKey) provider = 'tmdb-videos';
      } catch (err) {
        if (!(err instanceof ProviderError && err.status === 404)) logger.debug(`[ai-home] tmdb videos failed ${key}: ${err.message}`);
      }
    } else if ((m = /^jikan:anime:(\d+)$/.exec(key))) {
      try {
        const entry = await enrichJikan(m[1]);
        trailerKey = entry.trailerKey;
        if (trailerKey) {
          provider = 'jikan';
          resolvedTitle = resolvedTitle || entry.title;
          await putEnrichmentEntry(entry);
        }
      } catch (err) {
        logger.debug(`[ai-home] jikan trailer failed ${key}: ${err.message}`);
      }
    } else if ((m = /^db:(\d+)$/.exec(key))) {
      // Library row: follow its externalid, then fall back to a title search.
      try {
        const row = await getContentById(parseInt(m[1], 10));
        resolvedTitle = resolvedTitle || row?.title || null;
        const ext = String(row?.externalid || '');
        if (/^tmdb:(movie|tv):\d+$/.test(ext)) {
          const sub = await resolveTrailer(ext, row?.title);
          if (sub?.trailerKey && !sub?.error) {
            return { ...sub, key, cached: false };
          }
        }
      } catch {
        /* row missing — fall through to YouTube search */
      }
    }
  }

  // 3. YouTube Data API search fallback (works for any title).
  if (!trailerKey && (title || resolvedTitle)) {
    try {
      trailerKey = await searchYouTubeId(resolvedTitle || title);
      if (trailerKey) provider = 'youtube-search';
    } catch (err) {
      logger.debug(`[ai-home] youtube search failed: ${err.message}`);
    }
  }

  if (!trailerKey) {
    return {
      key,
      trailerKey: null,
      provider: null,
      title: resolvedTitle,
      embedUrl: null,
      cached: false,
      fetchedAt: new Date().toISOString(),
      note: 'No official trailer found in TMDB, Jikan or YouTube',
    };
  }

  await rememberTrailer(key, { trailerKey, provider, title: resolvedTitle });

  return {
    key,
    trailerKey,
    provider,
    title: resolvedTitle,
    embedUrl: `https://www.youtube.com/embed/${trailerKey}?autoplay=1&mute=1&controls=0&rel=0`,
    cached: false,
    fetchedAt: new Date().toISOString(),
  };
}

let warmRunning = false;
async function warmTrailers(keys) {
  if (warmRunning || !Array.isArray(keys) || keys.length === 0) return { queued: 0, skipped: 'busy-or-empty' };
  warmRunning = true;
  (async () => {
    try {
      for (const k of keys.slice(0, 24)) {
        await resolveTrailer(k, null);
        await new Promise((r) => setTimeout(r, 200));
      }
    } finally {
      warmRunning = false;
    }
  })();
  return { queued: Math.min(keys.length, 24) };
}

