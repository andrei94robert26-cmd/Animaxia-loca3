/** Extract a pending-enrichment queue from the library + trending head. */
async function enrichmentQueue() {
  const lib = await listContent({ page: 1, limit: 100, sort: 'createdat' });
  const queue = [];
  for (const row of lib.data || []) {
    const ext = String(row.externalid || '');
    let m;
    if ((m = /^tmdb:(movie|tv):(\d+)$/.exec(ext))) queue.push({ kind: 'tmdb', mediaType: m[1], id: m[2] });
    else if ((m = /^jikan:anime:(\d+)$/.exec(ext))) queue.push({ kind: 'jikan', id: m[1] });
  }
  // Rotating live pool: head of the trending chunk (cheap, already cached).
  try {
    const chunk = await externalChunk(1);
    chunk.slice(0, 14).forEach((item) => {
      if (item.mediaType === 'anime') queue.push({ kind: 'jikan', id: String(item.id) });
      else queue.push({ kind: 'tmdb', mediaType: item.mediaType, id: String(item.id) });
    });
  } catch {
    /* chunk unavailable — library-only pool */
  }
  // De-duplicate queue entries by their future store key.
  const seen = new Set();
  return queue.filter((q) => {
    const key = q.kind === 'tmdb' ? `tmdb:${q.mediaType}:${q.id}` : `jikan:anime:${q.id}`;
    if (seen.has(key)) return false;
    seen.add(key);
    return true;
  });
}

let enrichRunning = false;

/** Grow the enrichment pool by `batch` items (background-safe). */
async function enrichNext(batch) {
  if (enrichRunning) return { running: true, enriched: 0, skipped: 'already-running' };
  enrichRunning = true;
  let enriched = 0;
  const failed = 0;
  try {
    const store = await readEnrichment();
    const now = Date.now();
    const queue = await enrichmentQueue();
    const pending = queue.filter((q) => {
      const key = q.kind === 'tmdb' ? `tmdb:${q.mediaType}:${q.id}` : `jikan:anime:${q.id}`;
      const entry = store.entries[key];
      if (!entry) return true;
      return now - new Date(entry.fetchedAt).getTime() > ENRICH_TTL_MS;
    });
    let slot = 0;
    for (const q of pending) {
      if (enriched >= batch) break;
      try {
        let entry;
        if (q.kind === 'tmdb') entry = await enrichTmdb(q.mediaType, q.id);
        else entry = await enrichJikan(q.id);
        store.entries[entry.key] = entry;
        // Persist immediately (crash-safe per entry, Neon upsert).
        await putEnrichmentEntry(entry);
        // TMDB/Jikan trailers flow straight into the trailer store for free.
        if (entry.trailerKey) await rememberTrailer(entry.key, {
          trailerKey: entry.trailerKey,
          provider: entry.kind === 'tmdb' ? 'tmdb-videos' : 'jikan',
          title: entry.title,
        });
        enriched += 1;
        await new Promise((r) => setTimeout(r, 250)); // gentle on the providers
      } catch (err) {
        logger.debug(`[ai-home] enrich failed ${q.kind}:${q.id}: ${err.message}`);
      }
      slot += 1;
      if (slot > batch * 3) break; // don't churn on persistent failures
    }
  } finally {
    enrichRunning = false;
  }
  return { running: false, enriched, failed };
}

