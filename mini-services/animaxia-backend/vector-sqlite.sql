CREATE TABLE IF NOT EXISTS vectorembeddings (
 id INTEGER PRIMARY KEY AUTOINCREMENT,
 refkey TEXT UNIQUE NOT NULL,
 kind TEXT NOT NULL,
 refid INTEGER NOT NULL DEFAULT 0,
 userid INTEGER,
 dims INTEGER NOT NULL DEFAULT 256,
 embedding TEXT NOT NULL DEFAULT '[]',
 metadata TEXT NOT NULL DEFAULT '{}',
 contenttext TEXT,
 tenantid TEXT NOT NULL DEFAULT 'global',
 shardid INTEGER NOT NULL DEFAULT 0,
 createdat TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updatedat TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);
